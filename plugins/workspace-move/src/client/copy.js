export function errorText(error) {
  const code = error && typeof error === 'object' ? error.code : undefined
  if (typeof code === 'string' && Object.hasOwn(ERRORS, code)) return ERRORS[code]
  return '옮기지 못했어요. 잠시 뒤 다시 시도해 주세요.'
}
